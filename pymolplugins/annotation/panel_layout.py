    layout = QtWidgets.QVBoxLayout(panel)
    layout.setContentsMargins(20, 16, 20, 18)
    layout.setSpacing(14)
    _header(panel, layout)
    panel.error_label = QtWidgets.QLabel()
    panel.error_label.setWordWrap(True)
    panel.error_label.setOpenExternalLinks(False)
    panel.error_label.linkActivated.connect(panel._error_link)
    panel.error_label.setProperty("role", "error")
    panel.error_label.hide()
    layout.addWidget(panel.error_label)
    panel.main_tabs = QtWidgets.QStackedWidget()
    panel.review_tab = _review_page(panel)
    panel.source_tab = _source_page(panel)
