def _loading_settings(panel, layout):
    section = CollapsibleSection("Loading and preloading")
    form = QtWidgets.QFormLayout(section.content)
    choices = {
        "keep_previous_cb": "Keep previous structures visible in the session",
        "prefer_gz_cb": "Prefer compressed structures when both versions exist",
        "skip_annotated_cb": "Skip annotated structures when loading a directory",
        "preload_enabled_cb": "Preload upcoming structures",
        "bg_decompress_cb": "Prepare compressed structures in the background",
        "cache_enabled_cb": "Cache remote and compressed structures locally",
    }
    for name, title in choices.items():
        checkbox = QtWidgets.QCheckBox(title)
        checkbox.stateChanged.connect(panel._schedule_state_save)
        setattr(panel, name, checkbox)
        form.addRow(checkbox)
    panel.preload_ahead_spin = QtWidgets.QSpinBox()
    panel.preload_ahead_spin.setRange(0, 20)
    panel.preload_ahead_spin.valueChanged.connect(panel._schedule_state_save)
    panel.preload_interval_spin = QtWidgets.QSpinBox()
    panel.preload_interval_spin.setRange(50, 5000)
    panel.preload_interval_spin.setSuffix(" ms")
    panel.preload_interval_spin.valueChanged.connect(panel._schedule_state_save)
    form.addRow("Structures ahead:", panel.preload_ahead_spin)
    form.addRow("Preload interval:", panel.preload_interval_spin)
    layout.addWidget(section)


